const DAY_MS = 24 * 60 * 60 * 1000;
const MINUTE_MS = 60_000;

export interface AuthTokens {
  accessToken: string;
  refreshToken: string;
  /**
   * Admin sessions only: when the session ends whatever happens (the hard
   * maximum, ISO time), so the admin site can say so. Absent for everyone else.
   */
  sessionExpiresAt?: string;
}

/**
 * When an admin session that started at `startedAt` must end
 * (config.adminSession.maxHours later).
 */
function adminSessionEnd(startedAt: Date): number {
  return startedAt.getTime() + config.adminSession.maxHours * 60 * MINUTE_MS;
}

/**
 * Signs a fresh access token and creates+stores a new refresh token row for
 * `user`.
 *
 * `familyId` links the new token into an existing rotation chain. Omit it at
 * login to start a new chain — the row is then its own family root, which is
 * why the create is followed by a self-referencing update.
 *
 * ADMIN sessions are short (config.adminSession): a 10-minute access token,
 * and a refresh token that dies after 30 minutes unused — each refresh
 * renews it — and never outlives `sessionStartedAt` + 8 hours. Nothing an
 * admin holds is long-lived, and a stolen admin token is soon worthless.
 */
async function issueTokens(
  prisma: PrismaClient,
  user: Pick<User, "id" | "role">,
  now: Date = new Date(),
  familyId?: string,
  sessionStartedAt: Date = now,
): Promise<AuthTokens> {
  const admin = user.role === "ADMIN";
  const sessionEndsAt = adminSessionEnd(sessionStartedAt);
  const accessSeconds = admin
    ? Math.max(
        1,
        Math.floor(Math.min(config.adminSession.accessTokenMinutes * MINUTE_MS, sessionEndsAt - now.getTime()) / 1000),
      )
    : undefined;
  const accessToken = signAccessToken({ userId: user.id, role: user.role }, accessSeconds);

  const refreshToken = generateRefreshTokenValue();
  const expiresAt = admin
    ? new Date(Math.min(now.getTime() + config.adminSession.idleMinutes * MINUTE_MS, sessionEndsAt))
    : new Date(now.getTime() + TOKEN.REFRESH_TOKEN_TTL_DAYS * DAY_MS);

  const created = await prisma.refreshToken.create({
    data: {
      userId: user.id,
      tokenHash: sha256(refreshToken),
      expiresAt,
      // The same moment the session's times were worked out from: an admin
      // session's hard end is counted from the chain's first row, so it must
      // match the end reported at login exactly.
      createdAt: now,
      // Placeholder for a brand-new chain; replaced with the row's own id
      // immediately below, since cuid() is generated by the database layer.
      familyId: familyId ?? "",
    },
  });

  if (!familyId) {
    await prisma.refreshToken.update({
      where: { id: created.id },
      data: { familyId: created.id },
    });
  }

  return admin
    ? { accessToken, refreshToken, sessionExpiresAt: new Date(sessionEndsAt).toISOString() }
    : { accessToken, refreshToken };
}

export type SignupRole = "RIDER" | "DRIVER";

export interface SignupInput {
  phone: string;
  name: string;
  role: SignupRole;
  /** Verification token returned by /auth/verify-otp for purpose=SIGNUP. */
  verifiedToken: string;
  /**
   * The person ticked "I'm 18 or older and I agree to the Terms and Privacy
   * Policy". There is no account without it (routes/auth.ts refuses first).
   */
  ageAndTermsConfirmed: true;
}

export interface SignupResult extends AuthTokens {
  user: User & { driver: Driver | null };
}

/**
 * Creates a new User (and, for DRIVER, a pending Driver row with
 * isApproved=false and an empty profile awaiting completeDriverProfile).
 * Throws PhoneAlreadyRegisteredError if the phone is already registered.
 */
export async function signup(prisma: PrismaClient, input: SignupInput): Promise<SignupResult> {
  verifyVerificationToken(input.verifiedToken, input.phone, "SIGNUP");
  if (input.ageAndTermsConfirmed !== true) throw new TermsNotConfirmedError();

  const existing = await prisma.user.findUnique({ where: { phone: input.phone } });
  if (existing) {
    throw new PhoneAlreadyRegisteredError(input.phone);
  }

  const user = await prisma.user.create({
    data: {
      phone: input.phone,
      name: input.name,
      role: input.role,
      ...termsConfirmation(),
      // For DRIVER, create the pending Driver row (empty profile, isApproved=false)
      // in the same write and include it below, so the signup response carries the
      // same `user.driver` shape as /me and login. carMake stays null, so the
      // onboarding gate still correctly routes a new driver to onboarding.
      ...(input.role === "DRIVER" ? { driver: { create: { isApproved: false } } } : {}),
    },
    include: { driver: true },
  });

  const tokens = await issueTokens(prisma, user);
  return { user, ...tokens };
}

export interface LoginInput {
  phone: string;
  /** Verification token returned by /auth/verify-otp for purpose=LOGIN. */
  verifiedToken: string;
  /** The admin site is asking: only an allowed ADMIN account may log in. */
  adminSite?: boolean;
}

export interface LoginResult extends AuthTokens {
  user: User & { driver: Driver | null };
}

/**
 * Logs in an existing user. Throws UserNotFoundError if no open account
 * exists for the phone. A deleted account's phone is rewritten to
 * "deleted:<id>", so it can't match here anyway; the deletedAt check says so
 * explicitly rather than relying on that.
 */
export async function login(prisma: PrismaClient, input: LoginInput): Promise<LoginResult> {
  verifyVerificationToken(input.verifiedToken, input.phone, "LOGIN");

  const user = await prisma.user.findUnique({
    where: { phone: input.phone },
    include: { driver: true },
  });
  if (!user || user.deletedAt) {
    throw new UserNotFoundError(input.phone);
  }
  // An ADMIN account off the allowlist can't log in anywhere: there is
  // nothing else it could do, and a session would be one more thing to steal.
  if (user.role === "ADMIN" && !adminPhoneAllowed(user.phone)) {
    throw new AdminNotAllowedError(user.id);
  }
  // The admin site gets no session for a rider or driver (it used to issue
  // one and let the site throw it away).
  if (input.adminSite && user.role !== "ADMIN") {
    throw new NotAnAdminError(user.id);
  }

  const tokens = await issueTokens(prisma, user);
  return { user, ...tokens };
}

/**
 * Validates a refresh token and rotates it: the old token is revoked and a
 * new access + refresh token pair is issued, inheriting the same rotation
 * family. Unknown or expired tokens throw InvalidRefreshTokenError.
 *
 * THEFT DETECTION: refresh tokens are one-time — a successful refresh
 * revokes the token it consumed. So presenting an already-revoked token
 * means two parties hold the same token, i.e. one of them stole it, and we
 * cannot tell which is the legitimate client. The safe response is to revoke
 * the ENTIRE family (every token descended from that login) and force a full
 * re-authentication, which invalidates the attacker's copy too.
 *
 * NOTE: this makes concurrent refreshes with the same token look like theft.
 * The mobile client therefore single-flights refreshes (mobile-shared
 * auth/apiClient.ts) so simultaneous 401s share one call rather than firing
 * several with the same token.
 */
export async function refresh(
  prisma: PrismaClient,
  refreshToken: string,
  now: Date = new Date(),
): Promise<AuthTokens> {
  const tokenHash = sha256(refreshToken);

  const stored = await prisma.refreshToken.findFirst({
    where: { tokenHash },
    include: { user: true },
  });

  if (!stored) {
    throw new InvalidRefreshTokenError();
  }

  // The row this refresh uses up: normally the presented token itself.
  let consumed: { id: string } = stored;

  if (stored.revokedAt) {
    // A token rotated moments ago, presented again: the phone never got the
    // answer to its last refresh (lost connection, timeout). Honour it by
    // rotating the chain's live token in its place, so the user stays signed
    // in. That token is revoked here, so whoever might hold it is caught
    // the next time they use it.
    const head = await liveHeadOfRecentRotation(prisma, stored, now);
    if (!head) {
      // Reuse of a consumed token — burn the whole chain, including whatever
      // token the other party is currently holding.
      await prisma.refreshToken.updateMany({
        where: { familyId: stored.familyId, revokedAt: null },
        data: { revokedAt: now },
      });
      throw new RefreshTokenReuseError(stored.userId);
    }
    consumed = head;
  }

  // DELETE /me revokes every refresh token, so a deleted account should never
  // get here; refuse it anyway rather than mint it a new session.
  if (stored.expiresAt < now || stored.user.deletedAt) {
    throw new InvalidRefreshTokenError();
  }

  // An admin session ends at its hard maximum, counted from the login (the
  // chain's first token), or as soon as the number is off the allowlist.
  let sessionStartedAt = now;
  if (stored.user.role === "ADMIN") {
    const root =
      stored.familyId === stored.id
        ? stored
        : await prisma.refreshToken.findUnique({ where: { id: stored.familyId }, select: { createdAt: true } });
    sessionStartedAt = root?.createdAt ?? stored.createdAt;
    const ended = !adminPhoneAllowed(stored.user.phone)
      ? "not_allowlisted"
      : now.getTime() >= adminSessionEnd(sessionStartedAt)
        ? "max_length"
        : null;
    if (ended) {
      await prisma.refreshToken.updateMany({
        where: { familyId: stored.familyId, revokedAt: null },
        data: { revokedAt: now },
      });
      throw new AdminSessionEndedError(stored.userId, ended);
    }
  }

  // Per login (rotation chain) and per account, never per IP. Checked before
  // rotating, so a refused refresh leaves the token valid to try again.
  await enforce(
    [
      { rule: RULES.refreshSession, subject: stored.familyId },
      { rule: RULES.refreshUser, subject: stored.userId },
    ],
    now.getTime(),
  );

  await prisma.refreshToken.update({
    where: { id: consumed.id },
    data: { revokedAt: now },
  });

  return issueTokens(prisma, stored.user, now, stored.familyId, sessionStartedAt);
}

/** Longest rotation chain followed for a retry; a real retry is one or two hops. */
const MAX_RETRY_HOPS = 5;

/**
 * When presenting the revoked token `stored` is a retry of a rotation (see
 * refresh), the chain's live token that the retry should rotate instead;
 * otherwise null, and it is reuse.
 *
 * A rotation revokes the old row and creates the new one with the same
 * timestamp (refresh passes one `now` to both), so a revoked row's successor
 * is the family row created at its `revokedAt`. Revoked by a log out, or by
 * a burned family, there is no such row. Every step of the chain must be
 * within TOKEN.REFRESH_RETRY_GRACE_MINUTES, and it must end at a live token.
 */
async function liveHeadOfRecentRotation(
  prisma: PrismaClient,
  stored: { id: string; familyId: string; revokedAt: Date | null },
  now: Date,
): Promise<{ id: string } | null> {
  const oldest = now.getTime() - TOKEN.REFRESH_RETRY_GRACE_MINUTES * MINUTE_MS;
  let current = stored;
  for (let hop = 0; hop < MAX_RETRY_HOPS; hop += 1) {
    if (!current.revokedAt) return current;
    if (current.revokedAt.getTime() < oldest) return null;
    const successor = await prisma.refreshToken.findFirst({
      where: { familyId: current.familyId, createdAt: current.revokedAt, id: { not: current.id } },
      select: { id: true, familyId: true, revokedAt: true },
    });
    if (!successor) return null;
    current = successor;
  }
  return null;
}

/** Revokes a single refresh token (e.g. on logout). Throws InvalidRefreshTokenError if unknown/already revoked. */
export async function logout(
  prisma: PrismaClient,
  refreshToken: string,
  now: Date = new Date(),
  /** The push token of the install logging out: it stops getting this user's notifications. */
  pushToken?: string,
): Promise<void> {
  const tokenHash = sha256(refreshToken);

  const stored = await prisma.refreshToken.findFirst({ where: { tokenHash } });
  if (!stored || stored.revokedAt) {
    throw new InvalidRefreshTokenError();
  }

  await prisma.refreshToken.update({
    where: { id: stored.id },
    data: { revokedAt: now },
  });

  if (pushToken) {
    await prisma.pushToken.deleteMany({ where: { userId: stored.userId, token: pushToken } });
  }
}

/** Revokes all of a user's active refresh tokens (e.g. on suspected compromise). */
export async function revokeAllForUser(
  prisma: PrismaClient,
  userId: string,
  now: Date = new Date(),
): Promise<void> {
  await prisma.refreshToken.updateMany({
    where: { userId, revokedAt: null },
    data: { revokedAt: now },
  });
}

export interface CompleteDriverProfileInput {
  carMake: string;
  carModel: string;
  carColor: string;
  plate: string;
  /** Optional — Cloudinary upload deferred to a future pass. */
  photoUrl?: string;
}

/** Fills in the driver profile fields created (empty) at DRIVER signup. */
export async function completeDriverProfile(
  prisma: PrismaClient,
  userId: string,
  input: CompleteDriverProfileInput,
) {
  return prisma.driver.update({
    where: { userId },
    data: {
      carMake: input.carMake,
      carModel: input.carModel,
      carColor: input.carColor,
      plate: input.plate,
      ...(input.photoUrl !== undefined ? { photoUrl: input.photoUrl } : {}),
    },
  });
}
